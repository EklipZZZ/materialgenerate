export function cleanCodeContent(content: string): string {
  return content
    .replace(/```python\n?/gi, "")
    .replace(/```\n?/g, "")
    .replace(/^\s*\n+/, "")
    .replace(/\n+$/, "");
}

export function cleanManualContent(content: string): string {
  return content
    .replace(/```(?:markdown|md)?\n?/gi, "")
    .replace(/^[-─]{3,}$/gm, "")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/^\s*\n+/, "")
    .replace(/\n+$/, "");
}
